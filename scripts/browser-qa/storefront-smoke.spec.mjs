import {test,expect} from "@playwright/test"
const base="http://127.0.0.1:8000"
async function evidence(page,info,name){await page.screenshot({path:info.outputPath(name+".png"),fullPage:true})}
test("ARG-B01 Arabic RTL routes and canonical redirect",async({page,request},info)=>{
 expect((await page.goto("/"))?.status()).toBe(200)
 await expect(page.locator("html")).toHaveAttribute("lang","ar")
 await expect(page.locator("html")).toHaveAttribute("dir","rtl")
 await expect(page.locator("h1")).toBeVisible()
 await evidence(page,info,"b01-ar-home")
 await page.goto("/products")
 await expect(page.locator("main#main-content")).toBeVisible()
 const response=await request.get(base+"/ar/products?category=fixtures",{maxRedirects:0})
 expect(response.status()).toBe(308)
 expect(response.headers()["location"]).toContain("/products?category=fixtures")
})
test("ARG-B02 English LTR and language switch retains context",async({page},info)=>{
 await page.goto("/en/products?category=fixtures&q=QA")
 await expect(page.locator("html")).toHaveAttribute("lang","en")
 await expect(page.locator("html")).toHaveAttribute("dir","ltr")
 await expect(page.locator("a.lux-lang")).toHaveAttribute("href","/products?category=fixtures&q=QA")
 await page.locator("a.lux-lang").click()
 await expect(page).toHaveURL(base+"/products?category=fixtures&q=QA")
 await expect(page.locator("html")).toHaveAttribute("lang","ar")
 await evidence(page,info,"b02-switch")
})
test("ARG-B03 catalog categories/search and interactive gallery",async({page},info)=>{
 await page.goto("/en/products?category=fixtures")
 await expect(page.getByRole("navigation",{name:"Breadcrumb"})).toBeVisible()
 await expect(page.locator("h1")).toContainText("QA Fixtures")
 await expect(page.locator(".products-grid")).toBeVisible()
 await page.goto("/en/products?q=Fixture%201")
 await expect(page.locator(".products-grid")).toBeVisible()
 await page.goto("/en/products/qa-fixture-1")
 await expect(page.locator("h1")).toContainText("QA Catalog Fixture 1")
 const thumbnails=page.getByRole("button",{name:/QA Catalog Fixture 1.*2/})
 await expect(page.getByRole("group",{name:"Product images"})).toBeVisible()
 await expect(page.getByRole("button",{name:/QA Catalog Fixture 1.*1/})).toHaveAttribute("aria-pressed","true")
 await thumbnails.click()
 await expect(thumbnails).toHaveAttribute("aria-pressed","true")
 await expect(page.locator('[aria-live="polite"]')).toContainText("Image 2 of 2")
 await expect(page.locator(".detail-main-photo")).toHaveAttribute("src",/\/images\/two\.svg$/)
 await evidence(page,info,"b03-gallery")
})
test("ARG-B04 verifies EGP catalog context and cart stays disabled without the BFF",async({page,request},info)=>{
 await page.goto("/en/products/qa-fixture-1")
 await expect(page.locator(".detail-price")).toContainText(/EGP/)
 const ld=JSON.parse(await page.locator('script[type="application/ld+json"]').textContent())
 expect(ld["@type"]).toBe("Product")
 expect(ld).not.toHaveProperty("offers") // The MVP is catalog-only; no purchasable Offer
 const observed=await (await request.get("http://127.0.0.1:9091/__observed")).json()
 expect(observed.requests.some(r=>r.path==="/store/products"&&r.params.region_id==="reg_qa_egp"&&r.params.fields.includes("+variants.calculated_price"))).toBe(true)
 await expect(page.getByRole("button",{name:/Add to Cart/})).toBeDisabled()
 await expect(page.getByText("cart service is unavailable")).toBeVisible()
 await expect(page.getByText("Successfully added to cart")).toHaveCount(0)
 await evidence(page,info,"b04-egp")
})
test("ARG-B06 cart remains disabled and bilingual while checkout is unavailable",async({page},info)=>{
 await page.goto("/cart")
 await expect(page.locator("html")).toHaveAttribute("dir","rtl")
 await expect(page.getByRole("heading",{name:"سلة المشتريات"})).toBeVisible()
 await expect(page.getByRole("alert")).toContainText("خدمة السلة غير متاحة")
 await page.goto("/en/cart")
 await expect(page.locator("html")).toHaveAttribute("dir","ltr")
 await expect(page.getByRole("heading",{name:"Shopping Cart"})).toBeVisible()
 await expect(page.getByRole("alert")).toContainText("cart service is unavailable")
 await expect(page.getByRole("status")).toContainText("Purchasing actions are disabled")
 await page.goto("/en/checkout")
 await expect(page.locator('input[name="paymentMethod"][value="cod"]')).toBeDisabled()
 await expect(page.locator('input[name="paymentMethod"][value="electronic"]')).toBeDisabled()
 await expect(page.getByRole("button",{name:/Checkout Disabled/})).toBeDisabled()
 await evidence(page,info,"b06-checkout-disabled")
})
test("ARG-B05 mobile keyboard skip link and no overflow",async({page},info)=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto("/en/products/qa-fixture-1")
 await expect(page.getByRole("navigation",{name:"Main navigation"})).toBeVisible()
 await expect(page.getByRole("navigation",{name:"Main navigation"}).getByRole("link",{name:"Shop"})).toBeVisible()
 await page.keyboard.press("Tab")
 await expect(page.locator(".lux-skip-link")).toBeFocused()
 const metrics=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}))
 expect(metrics.scroll).toBeLessThanOrEqual(metrics.client+2)
 await evidence(page,info,"b05-mobile")
})

test("ARG-B02 regression: locale switch follows client-side catalog navigation",async({page},info)=>{
 await page.goto("/en")
 await page.locator('.lux-primary-nav a[href="/en/products"]').click()
 await expect(page).toHaveURL(base+"/en/products")
 await page.locator('a.lux-filter-link[href*="category=fixtures"]').click()
 await expect(page).toHaveURL(base+"/en/products?category=fixtures")
 await expect(page.locator("a.lux-lang")).toHaveAttribute("href","/products?category=fixtures")
 await evidence(page,info,"b02-spa-locale")
})
test("ARG-B03 regression: selected variant survives language switch",async({page},info)=>{
 await page.goto("/en/products/qa-fixture-1")
 await page.locator(".detail-variant-select").selectOption("v2")
 await expect(page).toHaveURL(base+"/en/products/qa-fixture-1?variant=v2")
 await expect(page.locator(".detail-price")).toContainText("45.75")
 await expect(page.locator("a.lux-lang")).toHaveAttribute("href","/products/qa-fixture-1?variant=v2")
 await page.locator("a.lux-lang").click()
 await expect(page).toHaveURL(base+"/products/qa-fixture-1?variant=v2")
 await expect(page.locator(".detail-variant-select")).toHaveValue("v2")
 await evidence(page,info,"b03-locale-variant")
})
