import {test,expect} from "@playwright/test"
const base="http://127.0.0.1:8000"
async function evidence(page,info,name){await page.screenshot({path:info.outputPath(name+".png"),fullPage:true})}
test("ARG-B01 Arabic RTL routes and canonical redirect",async({page,request},info)=>{
 expect((await page.goto("/"))?.status()).toBe(200)
 await expect(page.locator("html")).toHaveAttribute("lang","ar")
 await expect(page.locator("html")).toHaveAttribute("dir","rtl")
 await expect(page.locator("h1")).toBeVisible()
 await evidence(page,info,"b01-ar-home")
 await page.goto("/products")
 await expect(page.locator("main#main-content")).toBeVisible()
 const response=await request.get(base+"/ar/products?category=fixtures",{maxRedirects:0})
 expect(response.status()).toBe(308)
 expect(response.headers()["location"]).toContain("/products?category=fixtures")
})
test("ARG-B02 English LTR and language switch retains context",async({page},info)=>{
 await page.goto("/en/products?category=fixtures&q=QA")
 await expect(page.locator("html")).toHaveAttribute("lang","en")
 await expect(page.locator("html")).toHaveAttribute("dir","ltr")
 await expect(page.locator("a.lux-lang")).toHaveAttribute("href","/products?category=fixtures&q=QA")
 await page.locator("a.lux-lang").click()
 await expect(page).toHaveURL(base+"/products?category=fixtures&q=QA")
 await expect(page.locator("html")).toHaveAttribute("lang","ar")
 await evidence(page,info,"b02-switch")
})
test("ARG-B03 catalog categories/search and interactive gallery",async({page},info)=>{
 await page.goto("/en/products?category=fixtures")
 await expect(page.locator("h1")).toContainText("QA Fixtures")
 await expect(page.locator(".products-grid")).toBeVisible()
 await page.goto("/en/products?q=Fixture%201")
 await expect(page.locator(".products-grid")).toBeVisible()
 await page.goto("/en/products/qa-fixture-1")
 await expect(page.locator("h1")).toContainText("QA Catalog Fixture 1")
 const tabs=page.getByRole("tab")
 await expect(tabs).toHaveCount(2)
 await tabs.nth(1).click()
 await expect(tabs.nth(1)).toHaveAttribute("aria-selected","true")
 await expect(page.locator(".detail-main-photo")).toHaveAttribute("src",/\/images\/two\.svg$/)
 await evidence(page,info,"b03-gallery")
})
test("ARG-B04 verifies EGP region context and no purchase CTA",async({page,request},info)=>{
 await page.goto("/en/products/qa-fixture-1")
 await expect(page.locator(".detail-price")).toContainText(/EGP/)
 const ld=JSON.parse(await page.locator('script[type="application/ld+json"]').textContent())
 expect(ld.offers.priceCurrency).toBe("EGP")
 const observed=await (await request.get("http://127.0.0.1:9091/__observed")).json()
 expect(observed.requests.some(r=>r.path==="/store/products"&&r.params.region_id==="reg_qa_egp"&&r.params.fields.includes("+variants.calculated_price"))).toBe(true)
 await expect(page.getByRole("button",{name:/buy|purchase|checkout|اشتر|إتمام الطلب/i})).toHaveCount(0)
 await evidence(page,info,"b04-egp")
})
test("ARG-B05 mobile keyboard skip link and no overflow",async({page},info)=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto("/en/products/qa-fixture-1")
 await page.keyboard.press("Tab")
 await expect(page.locator(".lux-skip-link")).toBeFocused()
 const metrics=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}))
 expect(metrics.scroll).toBeLessThanOrEqual(metrics.client+2)
 await evidence(page,info,"b05-mobile")
})
